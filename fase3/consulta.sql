SELECT * FROM SENSOR_DADOS;

SELECT *
FROM SENSOR_DADOS
WHERE IRRIGACAO = 'ON';

SELECT ROUND(AVG(UMIDADE), 1) AS MEDIA_UMIDADE,
       ROUND(AVG(PH), 1) AS MEDIA_PH
FROM SENSOR_DADOS;

SELECT *
FROM SENSOR_DADOS
WHERE PH < 6.0 OR PH > 7.0;

SELECT IRRIGACAO,
       COUNT(*) AS QUANTIDADE
FROM SENSOR_DADOS
GROUP BY IRRIGACAO;

SELECT NITROGENIO,
       FOSFORO,
       POTASSIO,
       COUNT(*) AS TOTAL
FROM SENSOR_DADOS
GROUP BY NITROGENIO, FOSFORO, POTASSIO
ORDER BY TOTAL DESC;

SELECT *
FROM SENSOR_DADOS
ORDER BY UMIDADE DESC
FETCH FIRST 5 ROWS ONLY;
